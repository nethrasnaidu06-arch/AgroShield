import React, { useEffect, useState } from 'react';
import { AnimatePresence, motion } from 'motion/react';
import { Check, CheckCircle2, ChevronDown } from 'lucide-react';
import { api } from '../api/client.ts';
import { AlertCategory, AlertItem } from '../types/agroshield.ts';
import {
  DemoDisclaimerBar,
  ErrorBanner,
  LoadingSkeleton,
  MetricCell,
  PageHeader,
  StatusPulseDot,
} from '../components/ui/CommonPrimitives.tsx';

export function AlertCentrePage({ onAlertsChanged }: { onAlertsChanged?: () => void }) {
  const [alerts, setAlerts] = useState<AlertItem[]>([]);
  const [category, setCategory] = useState<string>('all');
  const [showResolved, setShowResolved] = useState(false);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [expandedIds, setExpandedIds] = useState<Record<string, boolean>>({});

  const toggleExpanded = (id: string) => {
    setExpandedIds((prev) => ({ ...prev, [id]: !prev[id] }));
  };

  const loadAlerts = async () => {
    setLoading(true);
    setError(null);
    try {
      const res = await api.getAlerts();
      setAlerts(res);
    } catch (err: any) {
      setError(err.message);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    loadAlerts();
  }, []);

  const handleAck = async (id: string) => {
    await api.acknowledgeAlert(id);
    await loadAlerts();
    onAlertsChanged?.();
  };

  const handleResolve = async (id: string) => {
    await api.resolveAlert(id);
    await loadAlerts();
    onAlertsChanged?.();
  };

  const filtered = alerts.filter((a) => {
    if (!showResolved && a.resolvedAt) return false;
    if (category !== 'all' && a.category !== category) return false;
    return true;
  });

  const activeAlerts = alerts.filter((a) => !a.resolvedAt);

  return (
    <div className="space-y-6">
      <PageHeader
        title="Alert & Notification Centre"
        subtitle="Unified dispatch queue for confirmed disease outbreaks, environmental risk warnings, ESP32 sensor offline notices, and inspection reminders."
        action={
          <label className="inline-flex items-center gap-2 text-xs text-slate-700 cursor-pointer bg-white border border-stone-200 px-3 py-2 rounded-md">
            <input
              type="checkbox"
              checked={showResolved}
              onChange={(e) => setShowResolved(e.target.checked)}
              className="rounded accent-emerald-800"
            />
            Include Resolved
          </label>
        }
      />

      <DemoDisclaimerBar text="Includes 35+ synthetic Karnataka demo alerts plus live alerts auto-generated by ESP32 sensor ingestion thresholds." />

      {error && <ErrorBanner message={error} onRetry={loadAlerts} />}

      <div className="grid grid-cols-2 lg:grid-cols-4 gap-4">
        <MetricCell label="Open Alerts" value={activeAlerts.length} tone="warning" />
        <MetricCell
          label="Disease Alerts"
          value={activeAlerts.filter((a) => a.category === AlertCategory.DISEASE).length}
          tone="danger"
        />
        <MetricCell
          label="Environmental Warnings"
          value={activeAlerts.filter((a) => a.category === AlertCategory.ENVIRONMENTAL).length}
        />
        <MetricCell
          label="Sensor & Inspection"
          value={
            activeAlerts.filter(
              (a) => a.category === AlertCategory.SENSOR || a.category === AlertCategory.INSPECTION
            ).length
          }
        />
      </div>

      <div className="inline-flex flex-wrap items-center gap-1 p-1 bg-white border border-stone-200 rounded-md">
        {[
          { id: 'all', label: 'All Categories' },
          { id: AlertCategory.DISEASE, label: 'Disease' },
          { id: AlertCategory.ENVIRONMENTAL, label: 'Environmental' },
          { id: AlertCategory.SENSOR, label: 'IoT Sensors' },
          { id: AlertCategory.INSPECTION, label: 'Inspections' },
        ].map((tab) => (
          <button
            key={tab.id}
            onClick={() => setCategory(tab.id)}
            className={`px-3 py-1.5 text-xs font-medium rounded ${
              category === tab.id ? 'bg-emerald-900 text-white' : 'text-slate-600 hover:text-slate-900'
            }`}
          >
            {tab.label}
          </button>
        ))}
      </div>

      {loading ? (
        <LoadingSkeleton rows={7} />
      ) : (
        <div className="bg-white border border-stone-200 rounded-lg divide-y divide-stone-100 overflow-hidden">
          <AnimatePresence initial={false}>
            {filtered.map((a) => {
              const isExpanded = Boolean(expandedIds[a.id]);
              return (
                <motion.div
                  key={a.id}
                  layout
                  initial={{ opacity: 0, x: -10 }}
                  animate={{ opacity: 1, x: 0 }}
                  exit={{ opacity: 0, x: 24, height: 0, paddingTop: 0, paddingBottom: 0 }}
                  transition={{ duration: 0.22, ease: [0.22, 1, 0.36, 1] }}
                  className="overflow-hidden"
                >
                  <div className="p-4 flex flex-col sm:flex-row sm:items-center justify-between gap-4 hover:bg-stone-50/70 transition-colors">
                    <div className="min-w-0 space-y-1">
                      <div className="flex flex-wrap items-center gap-2 text-xs">
                        {!a.acknowledged && !a.resolvedAt && (
                          <StatusPulseDot
                            variant={
                              a.severity === 'critical' || a.severity === 'high'
                                ? 'danger'
                                : a.severity === 'warning'
                                ? 'warning'
                                : 'online'
                            }
                          />
                        )}
                        <span
                          className={`font-semibold uppercase tracking-wide ${
                            a.severity === 'critical'
                              ? 'text-red-700'
                              : a.severity === 'high'
                              ? 'text-orange-700'
                              : a.severity === 'warning'
                              ? 'text-amber-700'
                              : 'text-slate-600'
                          }`}
                        >
                          {a.severity}
                        </span>
                        <span className="text-slate-300">·</span>
                        <span className="capitalize text-slate-600">{a.category}</span>
                        <span className="text-slate-300">·</span>
                        <span className="font-mono text-slate-400">{a.createdAt.slice(0, 16).replace('T', ' ')}</span>
                      </div>
                      <div className="text-sm font-semibold text-slate-900">{a.title}</div>
                      <p className="text-xs text-slate-600">{a.message}</p>
                      <div className="text-[11px] text-slate-500 flex flex-wrap items-center gap-2">
                        <span>
                          {a.farmName} {a.zoneName ? `· ${a.zoneName}` : ''}
                        </span>
                        <button
                          type="button"
                          onClick={() => toggleExpanded(a.id)}
                          className="inline-flex items-center gap-0.5 text-emerald-800 font-medium hover:underline"
                        >
                          <span>{isExpanded ? 'Hide Details' : 'View Details'}</span>
                          <ChevronDown
                            className={`w-3 h-3 transition-transform duration-200 ${
                              isExpanded ? 'rotate-180' : ''
                            }`}
                          />
                        </button>
                      </div>

                      <AnimatePresence initial={false}>
                        {isExpanded && (
                          <motion.div
                            initial={{ opacity: 0, height: 0 }}
                            animate={{ opacity: 1, height: 'auto' }}
                            exit={{ opacity: 0, height: 0 }}
                            transition={{ duration: 0.2, ease: [0.22, 1, 0.36, 1] }}
                            className="overflow-hidden"
                          >
                            <div className="mt-2 bg-stone-50 border border-stone-200 rounded-md p-2.5 text-[11px] text-slate-700 grid grid-cols-1 sm:grid-cols-3 gap-2">
                              <div>
                                <span className="text-slate-500 block">Alert ID</span>
                                <span className="font-mono text-slate-800">{a.id}</span>
                              </div>
                              <div>
                                <span className="text-slate-500 block">Acknowledgement</span>
                                <span className="font-medium text-slate-800">
                                  {a.acknowledged ? 'Acknowledged by operator' : 'Pending review'}
                                </span>
                              </div>
                              <div>
                                <span className="text-slate-500 block">Resolution State</span>
                                <span className="font-medium text-slate-800">
                                  {a.resolvedAt ? `Resolved (${a.resolvedAt.slice(0, 10)})` : 'Active Dispatch'}
                                </span>
                              </div>
                            </div>
                          </motion.div>
                        )}
                      </AnimatePresence>
                    </div>

                    <div className="flex items-center gap-2 shrink-0">
                      {!a.acknowledged && !a.resolvedAt && (
                        <button
                          onClick={() => handleAck(a.id)}
                          className="inline-flex items-center gap-1 px-3 py-1.5 text-xs font-medium border border-stone-200 rounded-md text-slate-700 hover:bg-stone-50"
                        >
                          <Check className="w-3.5 h-3.5" />
                          Acknowledge
                        </button>
                      )}
                      {!a.resolvedAt ? (
                        <button
                          onClick={() => handleResolve(a.id)}
                          className="inline-flex items-center gap-1 px-3 py-1.5 text-xs font-medium bg-emerald-900 text-white rounded-md hover:bg-emerald-800"
                        >
                          <CheckCircle2 className="w-3.5 h-3.5" />
                          Resolve
                        </button>
                      ) : (
                        <span className="text-xs font-medium text-emerald-700">Resolved</span>
                      )}
                    </div>
                  </div>
                </motion.div>
              );
            })}
          </AnimatePresence>
        </div>
      )}
    </div>
  );
}
